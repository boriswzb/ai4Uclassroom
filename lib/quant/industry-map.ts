// 构建代码前缀 -> 行业 映射（用于快速匹配）
// 前3位代码前缀覆盖大多数情况
const PREFIX_MAP = new Map<string, string>();

// 构建精确代码 -> 行业 映射
const CODE_MAP = new Map<string, string>();

for (const [code, industry] of PAIRS) {
  // 只保留每个代码第一次出现的映射（避免PAIRS中重复条目被错误覆盖）
  if (!CODE_MAP.has(code)) CODE_MAP.set(code, industry);
  // 前3位前缀（同样只保留第一个）
  const p3 = code.slice(0, 3);
  if (!PREFIX_MAP.has(p3)) PREFIX_MAP.set(p3, industry);
  // 前4位前缀
  const p4 = code.slice(0, 4);
  if (!PREFIX_MAP.has(p4)) PREFIX_MAP.set(p4, industry);
}

// 常见代码前缀 -> 行业（兜底）
const COMMON_PREFIXES: [string, string][] = [
  ['600','沪市主板'],['601','沪市主板'],['603','沪市主板'],['605','沪市主板'],
  ['688','科创板'],
  ['000','深市主板'],['001','深市主板'],['002','中小板'],
  ['300','创业板'],
  ['8','北交所'],['4','北交所'],
];

/**
 * 获取股票的行业分类
 */
export function getIndustry(code: string): string {
  // 去掉前后缀（支持 sh600519, sz000858, SH600519, .SZ, .SH, .BJ 等格式）
  const num = code.replace(/^[a-z]+/i, '').replace(/\.SZ$/i, '').replace(/\.SH$/i, '').replace(/\.BJ$/i, '');

  // 精确匹配
  if (CODE_MAP.has(num)) return CODE_MAP.get(num)!;

  // 尝试前4位
  const p4 = num.slice(0, 4);
  if (PREFIX_MAP.has(p4)) return PREFIX_MAP.get(p4)!;

  // 尝试前3位
  const p3 = num.slice(0, 3);
  if (PREFIX_MAP.has(p3)) return PREFIX_MAP.get(p3)!;

  // 前缀兜底
  for (const [prefix, fallback] of COMMON_PREFIXES) {
    if (num.startsWith(prefix)) return fallback;
  }

  return '其他';
}

/**
 * 获取所有行业列表（去重排序）
 */
export function getAllIndustries(): string[] {
  const industries = new Set<string>();
  for (const [, ind] of PAIRS) industries.add(ind);
  return [...industries].sort();
}
